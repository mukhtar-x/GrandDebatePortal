import { createHash, randomBytes } from "node:crypto";
import { Types, type ClientSession } from "mongoose";
import { calculatePricing, type Pricing } from "@/lib/pricing";
import type { RegistrationDetails } from "@/lib/registrationInput";
import Challan, { type ChallanCategory } from "@/models/Challan";
import ChallanIssue from "@/models/ChallanIssue";

export const CHALLAN_RESERVATION_MS = 30 * 60 * 1000;
export const CHALLAN_GRACE_MS = 15 * 60 * 1000;
export const CHALLAN_ENVIRONMENT: "test" | "live" = process.env.CHALLAN_MODE === "test"
    ? "test"
    : process.env.CHALLAN_MODE === "live" || process.env.NODE_ENV === "production" ? "live" : "test";
/** Earlier challans generated by the same email within this window are linked to its registration. */
const LINK_WINDOW_MS = 3 * 60 * 60 * 1000;

export function challanCategory(delegateCount: number): ChallanCategory {
    return (delegateCount === 1 ? "solo" : `delegation-${delegateCount}`) as ChallanCategory;
}

export function getChallanDetails(participantType: unknown, delegateCount: unknown, date = new Date()) {
    if ((participantType !== "solo" && participantType !== "delegation") || typeof delegateCount !== "number" || !Number.isInteger(delegateCount)) return null;
    const count = delegateCount as number;
    if (participantType === "solo" ? count !== 1 : count < 4 || count > 7) return null;
    const pricing = calculatePricing(count, date);
    if (!pricing.success) return null;
    return { category: challanCategory(count), ...pricing.pricing };
}

export function hashSecret(value: string): string {
    return createHash("sha256").update(value).digest("hex");
}

export function createReservationToken() {
    const token = randomBytes(32).toString("base64url");
    return { token, tokenHash: hashSecret(token) };
}

/** Stable hash of normalised registration details; any change to them needs a new challan. */
export function registrationFingerprint(value: unknown): string {
    const stable = (input: unknown): unknown => {
        if (Array.isArray(input)) return input.map(stable);
        if (input && typeof input === "object") {
            return Object.fromEntries(Object.entries(input as Record<string, unknown>)
                .sort(([a], [b]) => a.localeCompare(b))
                .map(([key, item]) => [key, stable(item)]));
        }
        return input;
    };
    return hashSecret(JSON.stringify(stable(value)));
}

/** A challan can be issued if it was never used, or its last holder's grace period has ended. */
export function reusableChallanFilter(now: Date) {
    return {
        $or: [
            { status: "Available" },
            { status: { $in: ["Reserved", "Expired"] }, graceUntil: { $lte: now } },
        ],
    };
}

/** Unused challans first, then the least reused, then the one released longest ago. */
export const CHALLAN_ISSUE_ORDER = { issueCount: 1, graceUntil: 1, challanNumber: 1 } as const;

const END_RESERVATION = {
    $unset: { reservationTokenHash: 1, registrationFingerprint: 1, reservationContactHash: 1, expiresAt: 1 },
} as const;

export interface ReservationView {
    challanNumber: string;
    amount: number;
    rateType: Pricing["rateType"];
    category: ChallanCategory;
    expiresAt: Date;
    graceUntil: Date;
}

export class NoChallanAvailableError extends Error {}

/**
 * Ends the reservation held by `tokenHash` early. The challan keeps its graceUntil, so it is not
 * issued to anyone else before the original grace period ends (a payment may still be on its way).
 */
export async function endReservation(
    tokenHash: string,
    issueStatus: "Released" | "Superseded",
    now: Date,
    session?: ClientSession,
): Promise<boolean> {
    const challan = await Challan.findOneAndUpdate(
        { environment: CHALLAN_ENVIRONMENT, reservationTokenHash: tokenHash, status: "Reserved" },
        { $set: { status: "Expired" }, ...END_RESERVATION },
        { session, returnDocument: "before" },
    ).select("currentIssueId").lean<{ currentIssueId?: Types.ObjectId }>();
    if (!challan) return false;
    if (challan.currentIssueId) {
        await ChallanIssue.updateOne(
            { _id: challan.currentIssueId, status: "Active" },
            { $set: { status: issueStatus, endedAt: now } },
            { session },
        );
    }
    return true;
}

/**
 * Atomically issues a challan for the registration and records who it was issued to.
 * Must run inside a transaction so the challan and its history record are written together.
 */
export async function issueChallan(input: {
    details: RegistrationDetails;
    pricing: Pricing;
    fingerprint: string;
    contactHash: string;
    tokenHash: string;
    ipHash: string;
    draftId?: string;
    now: Date;
    session: ClientSession;
}): Promise<ReservationView> {
    const { details, pricing, now, session } = input;
    const category = challanCategory(details.delegates.length);
    const expiresAt = new Date(now.getTime() + CHALLAN_RESERVATION_MS);
    const graceUntil = new Date(expiresAt.getTime() + CHALLAN_GRACE_MS);
    const issueId = new Types.ObjectId();

    const challan = await Challan.findOneAndUpdate(
        {
            environment: CHALLAN_ENVIRONMENT,
            category,
            rateType: pricing.rateType,
            amount: pricing.totalPayable,
            ...reusableChallanFilter(now),
        },
        {
            $set: {
                status: "Reserved",
                reservationTokenHash: input.tokenHash,
                registrationFingerprint: input.fingerprint,
                reservationContactHash: input.contactHash,
                currentIssueId: issueId,
                reservedAt: now,
                expiresAt,
                graceUntil,
            },
            $inc: { issueCount: 1 },
        },
        { sort: CHALLAN_ISSUE_ORDER, returnDocument: "after", session },
    ).lean<{ challanNumber: string; amount: number; rateType: Pricing["rateType"]; issueCount: number }>();
    if (!challan) throw new NoChallanAvailableError();

    await ChallanIssue.create([{
        _id: issueId,
        challanNumber: challan.challanNumber,
        environment: CHALLAN_ENVIRONMENT,
        category,
        rateType: challan.rateType,
        amount: challan.amount,
        issueNumber: challan.issueCount,
        participantType: details.participantType,
        institution: details.institution,
        contactName: details.contact.name,
        contactEmail: details.contact.email,
        contactWhatsapp: details.contact.whatsapp,
        delegateEmails: details.delegates.map(({ email }) => email),
        ...(details.baCode ? { baCode: details.baCode } : {}),
        ...(input.draftId ? { draftId: input.draftId } : {}),
        ipHash: input.ipHash,
        status: "Active",
        reservedAt: now,
        expiresAt,
        graceUntil,
    }], { session });

    return { challanNumber: challan.challanNumber, amount: challan.amount, rateType: challan.rateType, category, expiresAt, graceUntil };
}

/**
 * Records the submitted challan against the application, links every other challan the
 * applicant generated in this form fill (or recently with the same email), and frees any of
 * those still held. Returns the other challan numbers, oldest first.
 */
export async function recordSubmittedChallan(input: {
    challanIssueId?: Types.ObjectId;
    applicationId: string;
    contactEmail: string;
    draftId?: string;
    now: Date;
    session: ClientSession;
}): Promise<string[]> {
    const { applicationId, now, session } = input;
    if (input.challanIssueId) {
        await ChallanIssue.updateOne(
            { _id: input.challanIssueId },
            { $set: { status: "Submitted", applicationId, endedAt: now } },
            { session },
        );
    }

    const earlier = await ChallanIssue.find({
        environment: CHALLAN_ENVIRONMENT,
        ...(input.challanIssueId ? { _id: { $ne: input.challanIssueId } } : {}),
        applicationId: { $exists: false },
        linkedApplicationId: { $exists: false },
        $or: [
            ...(input.draftId ? [{ draftId: input.draftId }] : []),
            { contactEmail: input.contactEmail, reservedAt: { $gte: new Date(now.getTime() - LINK_WINDOW_MS) } },
        ],
    })
        .sort({ reservedAt: 1 })
        .select("_id challanNumber status graceUntil")
        .session(session)
        .lean<Array<{ _id: Types.ObjectId; challanNumber: string; status: string; graceUntil: Date }>>();
    if (earlier.length === 0) return [];

    await ChallanIssue.updateMany(
        { _id: { $in: earlier.map(({ _id }) => _id) } },
        { $set: { linkedApplicationId: applicationId } },
        { session },
    );
    const stillHeld = earlier.filter((issue) => issue.status === "Active" && new Date(issue.graceUntil) > now);
    if (stillHeld.length > 0) {
        const ids = stillHeld.map(({ _id }) => _id);
        await ChallanIssue.updateMany({ _id: { $in: ids } }, { $set: { status: "Superseded", endedAt: now } }, { session });
        await Challan.updateMany(
            { currentIssueId: { $in: ids }, status: "Reserved" },
            { $set: { status: "Expired" }, ...END_RESERVATION },
            { session },
        );
    }
    return [...new Set(earlier.map(({ challanNumber }) => challanNumber))];
}
